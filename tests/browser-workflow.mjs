  assert.match(await page.locator('#detail-body').textContent(),/<script>unsafe\(\)<\/script>/);
  assert.equal(await page.locator('#detail-body script').count(),0);
  const emailFrame = page.frameLocator('#email-frame');
  await emailFrame.getByRole('heading', { name:'Your subscription is confirmed' }).waitFor();
  assert.equal(await emailFrame.locator('table').count(),1);
  assert.equal(await emailFrame.locator('script,form,input').count(),0);
  assert.equal(await emailFrame.locator('img').count(),0);
  assert.equal(await page.locator('body').getAttribute('data-compromised'),null);
  assert.equal(await emailFrame.getByRole('link', {name:'Manage subscription'}).getAttribute('target'),'_blank');
  await page.locator('#toggle-format').click();
  assert.equal(await page.locator('#detail-body').isVisible(),true);
  await page.locator('#toggle-format').click();
  const remoteRequests = [];
  await page.route('https://images.example.invalid/**', route => { remoteRequests.push(route.request().url()); return route.fulfill({status:200,contentType:'image/png',body:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j3ioAAAAASUVORK5CYII=','base64')}); });
  assert.equal(remoteRequests.length,0); assert.equal(observedImages.length,0,'No tracking images before consent');
  await page.locator('#show-images').click();
  await emailFrame.locator('img').first().waitFor();
  await page.waitForFunction(() => document.querySelector('#email-frame')?.contentDocument?.images[0]?.complete);
  assert.ok(remoteRequests.length >= 1);
  await page.locator('#assign-summary').click(); await page.locator('#assign-me').click();
  await page.waitForFunction(() => document.querySelector('#detail-status')?.textContent === 'In progress');
  await page.locator('#finish-ticket').click();
  await page.waitForFunction(() => document.querySelector('#detail-status')?.textContent === 'Finished');
  await page.locator('.mail-filter-options > summary').click();
  await page.locator('#ticket-status').selectOption('finished'); await page.locator('#closed-filter').selectOption(f.owner);
  await page.waitForFunction(() => document.querySelector('#mail-feedback')?.textContent.includes('1 emails'));
  await page.locator('#reopen-ticket').click();
  await page.waitForFunction(() => document.querySelector('#detail-status')?.textContent === 'In progress');
  await page.waitForFunction(() => document.querySelectorAll('ticket-card').length === 0);
  await page.locator('button[type=reset]').click(); await page.locator('ticket-card button').first().waitFor();
  await page.locator('.export-dropdown > summary').click();
  const downloadText = page.waitForEvent('download'); await page.locator('#export-text').click();
  assert.match((await downloadText).suggestedFilename(),/-text\.eml$/);
  const downloadOriginal = page.waitForEvent('download'); await page.locator('#export-original').click();
  assert.match((await downloadOriginal).suggestedFilename(),/-original\.eml$/);
  await page.locator('#load-attachments').click();
  const attachment = page.waitForEvent('download'); await page.locator('#attachments button').click();
  assert.equal((await attachment).suggestedFilename(),'sample.txt');
  await page.locator('[data-compose=reply]').click(); await page.locator('#compose-panel textarea').fill('Browser test reply');
  await page.locator('#compose-panel button[type=submit]').click();
  await page.waitForFunction(() => document.querySelector('#mail-feedback')?.textContent.includes('accepted by Outlook'));
  await page.locator('[data-compose=forward]').click(); await page.locator('#compose-panel input').fill('recipient@example.invalid');
  await page.locator('#compose-panel textarea').fill('Browser test forward'); await page.locator('#compose-panel button[type=submit]').click();
  await page.waitForFunction(() => !document.querySelector('#compose-panel textarea'));
  await page.frameLocator('#email-frame').getByRole('heading', {name:'Your subscription is confirmed'}).waitFor();
  await mkdir('test-results', {recursive:true});
  await page.locator('.mail-filter-options > summary').click();
  await page.screenshot({path:'test-results/mailbox-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
