  await page.screenshot({path:'test-results/mailbox-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.route('**/emails/*/body', route => route.fulfill({status:503,contentType:'application/json',body:'{"message":"Microsoft unavailable"}'}));
  await page.locator('ticket-card button').first().click();
  await page.waitForFunction(() => document.querySelector('#reader-status')?.textContent.includes('formatted message unavailable'));
  assert.equal(await page.locator('#detail-body').isVisible(),true);
  assert.equal(await page.locator('#email-frame').isVisible(),false);
  await page.locator('a[href="compose.html"]').click(); await page.locator('#compose-form').waitFor({ state:'visible' });
  await page.locator('[name=to]').fill('recipient@example.invalid'); await page.locator('[name=subject]').fill('Browser compose');
  await page.locator('[name=body]').fill('New conversation'); await page.locator('#compose-form button[type=submit]').click();
  await page.waitForFunction(() => document.querySelector('#compose-status')?.textContent.includes('accepted by Outlook'));
  await page.waitForFunction(() => document.querySelector('#compose-history')?.textContent.includes('Browser compose'));
  assert.equal(f.sent.length,3);
  await page.locator('a[href="settings.html"]').click(); await page.locator('#token-form').waitFor({ state:'visible' });
  assert.equal(await page.locator('#outlook-token').inputValue(),'');
  await page.locator('#outlook-token').fill('browser-synthetic-token'); await page.locator('#token-form button').click();
  await page.waitForFunction(() => document.querySelector('#token-feedback')?.textContent.includes('verified and saved'));
  assert.equal(await page.locator('#outlook-token').inputValue(),'');
  await page.locator('#create-user-form [name=email]').fill(`browser-${f.key}@example.invalid`);
  await page.locator('#create-user-form [name=password]').fill(f.password); await page.locator('#create-user-form button').click();
