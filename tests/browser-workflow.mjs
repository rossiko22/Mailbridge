  assert.deepEqual(errors,[]);
  console.log('Browser passed: real login, synchronization, escaped mail, search/filter/reset, assignment, finish/reopen, EML/attachment downloads, reply/forward, compose/history, connection settings, team member creation, mobile layout and logout. No real mail sent.');
